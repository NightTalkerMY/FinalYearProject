#!/usr/bin/env python3
"""Print previously generated Objective 2 evaluation reports.

Unlike eval.py, this script reads the saved CSV files directly and does not
require the original metric_tests trial data.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd


DEFAULT_REPORTS_DIR = Path(__file__).resolve().parent / "reports"

REPORTS = (
    (
        "OBJECTIVE 2: TRIGGER-BASED RESULTS TABLE",
        "objective2_trigger_table.csv",
    ),
    (
        "OBJECTIVE 2: LIGHTING-BASED RESULTS TABLE",
        "objective2_lighting_table.csv",
    ),
)


def print_csv_table(title: str, path: Path) -> bool:
    """Load and print one CSV report, returning False if it is unavailable."""
    if not path.is_file():
        print(f"\n[NOT FOUND] {path}")
        return False

    try:
        table = pd.read_csv(path)
    except Exception as error:
        print(f"\n[ERROR] Could not read {path}: {error}")
        return False

    print(f"\n=== {title} ===")
    if table.empty:
        print("The report is empty.")
    else:
        print(table.to_string(index=False))
    return True


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Print the CSV reports previously generated by eval.py."
    )
    parser.add_argument(
        "--reports-dir",
        type=Path,
        default=DEFAULT_REPORTS_DIR,
        help=f"Directory containing the report CSVs (default: {DEFAULT_REPORTS_DIR})",
    )
    parser.add_argument(
        "--show-trials",
        action="store_true",
        help="Also print every row from objective2_trial_level_metrics.csv.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    reports_dir = args.reports_dir.expanduser().resolve()

    print(f"Loading saved evaluation reports from: {reports_dir}")

    loaded = 0
    for title, filename in REPORTS:
        loaded += print_csv_table(title, reports_dir / filename)

    if args.show_trials:
        loaded += print_csv_table(
            "OBJECTIVE 2: TRIAL-LEVEL METRICS",
            reports_dir / "objective2_trial_level_metrics.csv",
        )

    if loaded == 0:
        print("\nNo saved reports were found. Generate them with eval.py first.")
        return 1

    print("\nSaved report files:")
    for path in sorted(reports_dir.iterdir() if reports_dir.is_dir() else []):
        if path.is_file() and path.suffix.lower() in {".csv", ".png"}:
            print(f" - {path.name}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
